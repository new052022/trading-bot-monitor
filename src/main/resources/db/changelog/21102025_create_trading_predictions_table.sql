-- Table for storing trading predictions fetched from the quant service
CREATE TABLE trading_predictions (
    id BIGINT PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY, -- Corresponds to @Id, @GeneratedValue, Long id
    user_id BIGINT NOT NULL, -- Corresponds to @Column(name = "user_id"), Long userId
    prediction_data TEXT NOT NULL, -- Corresponds to @Column(name = "prediction_data"), String predictionData - stores JSON
    generated_at TIMESTAMP NOT NULL, -- Corresponds to @Column(name = "generated_at"), LocalDateTime generatedAt
    fetched_at TIMESTAMP NOT NULL -- Corresponds to @Column(name = "fetched_at"), LocalDateTime fetchedAt
);

-- Create index on user_id and fetched_at for faster queries
CREATE INDEX idx_trading_predictions_user_id_fetched_at ON trading_predictions(user_id, fetched_at DESC);

